'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');const box={window:{},console,Math,Date,Number,JSON,Array,Set,Map,Intl};vm.createContext(box);
for(const file of ['js/config.js','js/core/ProgressionSystem.js','js/core/GameState.js','js/core/TimeSystem.js','js/core/EconomySystem.js','js/core/SadakaSystem.js','js/core/LandFamilySystem.js']){
 vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),box,{filename:file});Object.assign(box,box.window);
}
const S=box.OasisSadaka,G=box.OasisGameState,C=box.OASIS_CONFIG;
const start=1000000000000,day=120*60000;
let state=G.createNew();state.createdAt=start;state.coins=50000;
assert.equal(C.dayMinutes,60);assert.equal(C.nightMinutes,60);
const first=S.list(state,start);assert(first.length>=6);assert.equal(state.charity.nextRefreshDay,3);assert.equal(S.gameDay(state,start+day*3),3);
const water=first.find(q=>q.coins===15);assert(water,'old requests must survive migration');
const before=state.coins,help=S.donate(state,water.id,start);
assert(help.ok&&state.coins===before-15);assert(help.blessing.text&&help.blessing.reply);
assert.equal(S.donate(state,water.id,start).ok,false,'same request only once');
assert(S.list(state,start+day*2).every(q=>!q.id.includes('-w1')),'too early for new requests');
const day3=S.list(state,start+day*3);assert(day3.some(q=>q.id.includes('-w1')),'new requests missing at day 3');
assert.equal(state.charity.nextRefreshDay,7,'next refresh must be after 4 game days');
assert(S.list(state,start+day*6).every(q=>!q.id.includes('-w2')));
assert(S.list(state,start+day*7).some(q=>q.id.includes('-w2')),'new requests missing at day 7');
assert.equal(state.charity.nextRefreshDay,10,'subsequent wave after 3 game days');
const w1=new Set(S.list(state,start+day*7).filter(r=>r.wave===1).map(r=>r.title));
const w2=S.list(state,start+day*7).filter(r=>r.wave===2).map(r=>r.title);
assert(w2.every(name=>!w1.has(name)),'consecutive waves should avoid repeated titles');
assert(S.list(state,start+day*50).filter(x=>!x.done).length<=12,'requests must remain manageable after offline time');
const projects=S.projects(state,start+day*50);assert(projects.length>=4);
for(const id of ['mosque','school','hospital','well'])assert(projects.find(p=>p.id===id));
const mosque=projects.find(p=>p.id==='mosque');assert.equal(mosque.raised,0);
let oldCoins=state.coins;assert(S.contribute(state,'mosque',10,start+day*50).ok);
assert.equal(state.coins,oldCoins-10);assert.equal(S.projects(state)[0].raised,10);
assert(S.contribute(state,'mosque',200).ok);assert.equal(S.projects(state)[0].raised,210);
assert.equal(S.contribute(state,'mosque',0).ok,false);
assert.equal(S.contribute(state,'mosque',-1).ok,false);
assert.equal(S.contribute(state,'mosque',1.5).ok,false);
assert.equal(S.contribute(state,'mosque',10000).ok,false,'must not overpay goal');
state=G.normalize(JSON.parse(JSON.stringify(state)));
assert.equal(S.projects(state)[0].raised,210,'partial project survives save reload');
const left=S.projects(state)[0].remaining;assert(S.contribute(state,'mosque',left).ok);
assert.equal(S.projects(state)[0].completed,true);
assert.equal(S.contribute(state,'mosque',1).ok,false,'completed projects stay closed');
assert(state.barakatLevel>0,'secret barakat should still work in model');
assert.equal(S.BLESSINGS.length,4);
for(const b of S.BLESSINGS){assert(b.text.includes('Аллах'));assert(['Амин','И вам того же'].includes(b.reply));}
assert.equal(S.BLESSINGS.find(b=>b.text==='Да воздаст тебе Аллах благом!').reply,'И вам того же');
assert(S.BLESSINGS.filter(b=>b.reply==='Амин').length===3);
console.log('PASS v1.7: alternate 3/4 game-day requests, offline rotation, 5 campaigns, partial donations, persistence, completion, secret effect, 4 matching replies');
