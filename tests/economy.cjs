'use strict';
const assert=require('assert'),fs=require('fs'),vm=require('vm'),path=require('path');
const root=path.resolve(__dirname,'..');
const box={window:{},Date,Math,Array,Object,Number,Set};vm.createContext(box);
for(const f of ['js/config.js','js/core/GameState.js','js/core/TimeSystem.js','js/core/ProgressionSystem.js','js/core/EconomySystem.js','js/core/DailyQuestSystem.js'])vm.runInContext(fs.readFileSync(path.join(root,f),'utf8'),box,{filename:f});Object.assign(box,box.window);
const E=box.OasisEconomy,G=box.OasisGameState;
let s=G.createNew();
assert.strictEqual(s.seedBank.clover,3);assert.strictEqual(s.seedBank.watermelon,2);
let coins=s.coins,now=Date.now();
assert(E.plant(s,45,'clover',now).ok);assert.strictEqual(s.seedBank.clover,2);assert.strictEqual(s.coins,coins);
assert(!E.harvest(s,45,now+100).ok);let h=E.harvest(s,45,now+151000);
assert(h.ok&&h.seedReturned===1);assert.strictEqual(s.seedBank.clover,3);assert.strictEqual(s.inventory.clover,2);assert.strictEqual(s.tiles[45].crop,null);
for(let i=0;i<4;i++){assert(E.plant(s,45,'clover',now+200000+i*200000).ok);assert(E.harvest(s,45,now+351000+i*200000).ok);}
assert.strictEqual(s.seedBank.clover,3,'seeds must survive repeated harvests');
let buy=E.buySeed(s,'clover',2);assert(buy.ok);assert.strictEqual(s.seedBank.clover,5);assert.strictEqual(s.coins,coins-6);
assert(!E.buySeed(s,'clover',101).ok);assert(!E.buySeed(s,'dates',1).ok);
s.totalSold=1850;s.coins=500;
assert(E.buySeed(s,'fig',1).ok);assert(E.plant(s,65,'fig',now).ok);
let first=E.harvest(s,65,now+601000);assert(first.ok&&first.perennial);
assert.strictEqual(s.tiles[65].crop,'fig');assert.strictEqual(s.tiles[65].perennialEstablished,true);assert.strictEqual(s.seedBank.fig,1,'tree should also provide a new cutting');
const second=E.harvest(s,65,now+1300000);assert(second.ok);assert.strictEqual(s.inventory.fig,6);
let before=s.totalSold;const sold=E.sell(s,'fig',2);assert(sold.ok&&sold.net>0);assert(s.totalSold>before);assert.strictEqual(s.inventory.fig,4);
E.ensureOrders(s);assert.strictEqual(s.orders.length,6);
let oldOrder=s.orders[0];s.inventory[oldOrder.id]=oldOrder.quantity;
assert(E.completeOrder(s,0).ok);assert.strictEqual(s.ordersCompleted,1);assert.strictEqual(s.inventory[oldOrder.id],0);
assert(!E.completeOrder(s,7).ok);
let legacy=G.normalize({coins:235,inventory:{clover:10},tiles:[{crop:'watermelon',plantedAt:now-60000}],totalSold:112});
assert.strictEqual(legacy.coins,235);assert.strictEqual(legacy.inventory.clover,10);assert.strictEqual(legacy.tiles[3*16+3].crop,'watermelon');assert.strictEqual(legacy.tiles.length,256);
assert(legacy.seedBank.clover>=3&&legacy.seedBank.watermelon>=2);
let legacyRoundtrip=G.normalize(JSON.parse(JSON.stringify(legacy)));assert.strictEqual(legacyRoundtrip.seedBank.clover,legacy.seedBank.clover,'migration must not duplicate starter seeds');
let empty=G.createNew();empty.seedBank.clover=0;empty.seedBank.watermelon=0;
assert(E.recoverySeed(empty,now).ok);assert.strictEqual(empty.seedBank.clover,1);
assert(!E.recoverySeed(empty,now+100).ok);
console.log('PASS: starter seeds, free replanting, buy seeds, perennial repeat harvest, sale, orders, save migration, no duplication, recovery');
